  var STORE = 'portfolio-lang-v2';
  var FR = {};

  function collect() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (!(k in FR)) FR[k] = el.innerHTML;
    });
  }

  function setLang(lang, save) {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      var v = (lang === 'en' && EN[k] !== undefined) ? EN[k] : FR[k];
      if (v !== undefined) el.innerHTML = v;
    });
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      var on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('active', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
    if (save) { try { localStorage.setItem(STORE, lang); } catch (e) {} }
  }

  function init() {
    collect();
    // Le travail demandé est d'abord en anglais : le site s'ouvre en anglais, sauf si le visiteur a choisi le français.
    var lang = 'en';
    try { lang = localStorage.getItem(STORE) || 'en'; } catch (e) {}
    if (lang !== 'fr') lang = 'en';
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.addEventListener('click', function () { setLang(b.getAttribute('data-lang'), true); });
    });
    setLang(lang, false);
    document.documentElement.classList.remove('i18n-wait');
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
